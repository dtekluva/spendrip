"""
Build SpenDrip's icons from manifest.json, for the app and the website.

    python3 design/icons/build.py

Writes:
  frontend/src/icons/icons.gen.ts   every UI icon (in the weights it lists), the plan icons, emoji and category maps
  frontend/src/icons/icons.gen.css  plan tile colours, per look
  landing/icons.css                 the same tile colours for the website
  landing/**/index.html             the <symbol>s each page uses (#i-<name>-<r|f|d>, #i-plan-<key>), inlined between
                                    <!-- icons:start --> and <!-- icons:end -->

Phosphor comes from frontend/node_modules/@phosphor-icons/core (a dev dependency); SpenDrip's own icons are in custom/.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PHOSPHOR = ROOT / "frontend/node_modules/@phosphor-icons/core/assets"
WEIGHTS = {"r": ("regular", ""), "f": ("fill", "-fill"), "d": ("duotone", "-duotone")}
# The duotone back layer takes its colour from CSS variables, so it works inline and through <use>.
ACC = 'style="fill:var(--duo-acc,currentColor);opacity:var(--duo-op,.2)"'


def body(svg: str) -> str:
    inner = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg.strip(), flags=re.S)
    return inner.replace('opacity="0.2"', ACC).strip()


def glyph(src: str, w: str) -> str:
    folder, suffix = WEIGHTS[w]
    if src.startswith("custom:"):
        return body((HERE / "custom" / f"{src[7:]}{suffix}.svg").read_text())
    return body((PHOSPHOR / folder / f"{src}{suffix}.svg").read_text())


def plain(emoji: str) -> str:
    """The emoji without skin tones or variation selectors, so 🙏🏾 and 🙏 find the same icon."""
    return re.sub("[\U0001F3FB-\U0001F3FF️]", "", emoji)


def main():
    m = json.loads((HERE / "manifest.json").read_text())
    ui = {name: {w: glyph(d["src"], w) for w in d["w"]} for name, d in m["ui"].items()}
    plans = [{**{k: p[k] for k in ("key", "label", "emoji", "hue")}, "chart": p.get("chart") or m["hues"][p["hue"]]["bg"],
              "glyph": glyph(p["icon"], "f")} for p in m["plans"]]
    emoji = {}
    for p in m["plans"]:
        for e in [p["emoji"], *p["also"]]:
            emoji.setdefault(plain(e), p["key"])

    ts = ["// Generated by design/icons/build.py from design/icons/manifest.json. Don't edit by hand.",
          f"export const UI = {json.dumps(ui, ensure_ascii=False, indent=0)} as const;",
          "export type IconName = keyof typeof UI;",
          "export type Weight = 'r' | 'f' | 'd';",
          f"export const PLANS = {json.dumps(plans, ensure_ascii=False, indent=0)} as const;",
          "export type PlanKey = (typeof PLANS)[number]['key'];",
          f"export const EMOJI: Record<string, PlanKey> = {json.dumps(emoji, ensure_ascii=False)};",
          f"export const CATEGORY: Record<string, PlanKey> = {json.dumps(m['categories'])};", ""]
    out = ROOT / "frontend/src/icons"
    out.mkdir(exist_ok=True)
    (out / "icons.gen.ts").write_text("\n".join(ts))

    # Tile colours: the plain value everywhere, the brighter one on the navy (themed) and dark looks.
    head = "/* Generated by design/icons/build.py from design/icons/manifest.json. */\n"
    light = "".join(f".pt-{k}{{--pt-bg:{h['bg']};--pt-ink:{h['ink']}}}\n" for k, h in m["hues"].items())
    navy = lambda scope: "".join(f"{scope}.pt-{k}{{--pt-bg:{h['themed']}}}\n" for k, h in m["hues"].items())
    (out / "icons.gen.css").write_text(head + light + navy(':is([data-look="themed"],[data-look="dark"]) '))
    (ROOT / "landing/icons.css").write_text(head + light + "@media (prefers-color-scheme: dark){\n" + navy("") + "}\n")

    # Website: inline the symbols each page uses.
    symbols = {f"i-{n}-{w}": g for n, ws in ui.items() for w, g in ws.items()}
    symbols.update({f"i-plan-{p['key']}": p["glyph"] for p in plans})
    for page in sorted((ROOT / "landing").rglob("*.html")):
        html = page.read_text()
        if "<!-- icons:start -->" not in html:
            continue
        used = sorted(set(re.findall(r'href="#(i-[a-z0-9-]+)"', html)))
        missing = [u for u in used if u not in symbols]
        if missing:
            raise SystemExit(f"{page.relative_to(ROOT)} uses unknown icons: {', '.join(missing)}")
        sprite = ('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">'
                  + "".join(f'<symbol id="{u}" viewBox="0 0 256 256" fill="currentColor">{symbols[u]}</symbol>' for u in used) + "</svg>")
        html = re.sub(r"<!-- icons:start -->.*?<!-- icons:end -->", f"<!-- icons:start -->{sprite}<!-- icons:end -->", html, flags=re.S)
        page.write_text(html)
        print(f"{page.relative_to(ROOT)}: {len(used)} icons")
    print(f"{len(ui)} UI icons, {len(plans)} plan icons, {len(emoji)} emoji")


if __name__ == "__main__":
    main()
